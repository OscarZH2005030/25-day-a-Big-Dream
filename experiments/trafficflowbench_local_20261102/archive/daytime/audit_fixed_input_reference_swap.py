"""Score identical predictions under two count-compatible artificial references."""
import hashlib
import msvcrt

import common as d
import numpy as np
import pandas as pd
import task4_span_shrink_stress as base
from verify_cycle_budget import score


def main():
    source = d.OUT/'task4_count_invariant_drift'
    out = d.OUT/'task4_fixed_input_reference_swap'
    d.save(out/'protocol.json',dict(
        scope='Posthoc counterfactual on existing artificial cases. Fix original inputs, priors and predictions, then swap only the latent reference.',
        qualification='References have the same counts and both margins. The alternate reference is a physical counterexample, without a claim that the original prior was generated by the alternate reference under the same noise law.',
        case_table_sha256=d.sha(source/'all_cases.csv'),source_sha256=d.sha(__file__)))
    rows=[]
    cases=pd.read_csv(source/'all_cases.csv')
    for panel,group in cases.groupby('panel'):
        paths,A,_,_,_=base.load(panel,'train')
        dest=pd.factorize(paths.destination_zone,sort=True)[0]
        for case,actions in group.groupby('case'):
            key=hashlib.sha256(case.encode()).hexdigest()[:16]
            folder=d.WORK/'task4_count_invariant_drift_cases'/key
            original_file=folder/'moderate.npz'
            alternate_file=folder/'repaired.npz'
            assert set(actions[actions.variant=='moderate'].artifact_sha256)=={d.sha(original_file)}
            assert set(actions[actions.variant=='repaired'].artifact_sha256)=={d.sha(alternate_file)}
            with np.load(original_file) as original,np.load(alternate_file) as alternate:
                prior,counts=original['prior'][2],original['counts'][2]
                for reference,z in [('original',original),('alternate',alternate)]:
                    truth=z['truth']
                    np.testing.assert_allclose(A@truth,counts,rtol=1e-12,atol=1e-9)
                    baseline_od,baseline_total=score(original['baseline'],truth,prior,A,counts,dest)
                    for method in ['raw005','clipped005']:
                        od,total=score(original[method],truth,prior,A,counts,dest)
                        rows.append(dict(case=case,panel=panel,noise=actions.noise.iloc[0],reference=reference,
                                         method=method,od_delta=od-baseline_od,composite_delta=total-baseline_total))
    frame=pd.DataFrame(rows)
    frame.to_csv(out/'by_case.csv',index=False)
    paired=frame.pivot(index=['noise','method','case'],columns='reference',values='od_delta')
    paired['positive_to_negative']=(paired.original>1e-12)&(paired.alternate< -1e-12)
    paired['negative_to_positive']=(paired.original< -1e-12)&(paired.alternate>1e-12)
    paired.to_csv(out/'paired_od.csv')
    paired.groupby(level=['noise','method']).agg(
        cases=('original','count'),mean_original=('original','mean'),mean_alternate=('alternate','mean'),
        positive_to_negative=('positive_to_negative','sum'),negative_to_positive=('negative_to_positive','sum')).to_csv(out/'summary.csv')
    d.state(status='stage_complete',stage='fixed_input_reference_swap_complete',
            next='Review sign reversals under identical observed inputs. Counterfactual references are not a calibrated prior-noise model.')


if __name__=='__main__':
    with (d.ROOT/'work/overnight/research.lock').open('r+b') as lock:
        msvcrt.locking(lock.fileno(),msvcrt.LK_NBLCK,1)
        main()
